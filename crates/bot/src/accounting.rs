//! Double-Entry Game Accounting (`L_acct`), Antisymmetric Residual Neural Network
//! (`Delta_sym`), and Accounting-Guided Tactical Simultaneous-Move Nash Minimax
//! (`compact_tactical_minimax_leaf`) on the 192-byte [`CompactBattle`] kernel.
//!
//! Architectural layers:
//! 1. **Layer 1 (Outer Tree)**: Existing MCTS / determinized [`crate::blind::BlindSearch`]
//!    handles multi-turn planning and hidden-set belief sampling.
//! 2. **Layer 2 (Tactical P/L Settlement — [`LeafSettlementMode::Minimax1`] / [`LeafSettlementMode::Quiesce2`])**:
//!    Replaces the noisy 8-turn `eps = 0.2` greedy rollout with a zero-leakage,
//!    variance-free simultaneous-move Nash minimax over each side's top-$K$
//!    accounting-ranked candidate actions, including exact `request == 2`
//!    post-KO / Baton-Pass receiver settlement, exact `60 / 256` Quick Claw
//!    weighting, and exact `50 / 50` speed-tie splitting.
//! 3. **Layer 3 (Balance-Sheet Stock Accounting + Strict-Search Residual NN)**:
//!    Prices quiescent boards via 16 double-entry accounting accounts
//!    (`basis_diff`) plus an antisymmetric `48 -> 32 -> 16 -> 1` HardSwish
//!    residual MLP $\Delta_{\text{sym}}(s) = f_\theta(\phi(s, 0)) - f_\theta(\phi(s, 1))$.

