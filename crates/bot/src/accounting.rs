#[derive(Clone, Debug, serde::Serialize, serde::Deserialize)]
struct AcctModelJson {
    w_acct: Vec<f32>,
    residual_scale: f32,
    residual_active: bool,
    w1: Vec<Vec<f32>>,
    b1: Vec<f32>,
    w2: Vec<Vec<f32>>,
    b2: Vec<f32>,
    w3: Vec<f32>,
}

impl From<AcctModel> for AcctModelJson {
    fn from(m: AcctModel) -> Self {
        Self {
            w_acct: m.w_acct.to_vec(),
            residual_scale: m.residual_scale,
            residual_active: m.residual_active,
            w1: m.w1.iter().map(|r| r.to_vec()).collect(),
            b1: m.b1.to_vec(),
            w2: m.w2.iter().map(|r| r.to_vec()).collect(),
            b2: m.b2.to_vec(),
            w3: m.w3.to_vec(),
        }
    }
}

impl TryFrom<AcctModelJson> for AcctModel {
    type Error = String;
    fn try_from(j: AcctModelJson) -> Result<Self, Self::Error> {
        if j.w_acct.len() != ACCT_BASIS_DIM {
            return Err(format!("w_acct len {} != {}", j.w_acct.len(), ACCT_BASIS_DIM));
        }
        if j.w1.len() != ACCT_H1 || j.b1.len() != ACCT_H1 {
            return Err(format!("w1/b1 len != {ACCT_H1}"));
        }
        if j.w2.len() != ACCT_H2 || j.b2.len() != ACCT_H2 || j.w3.len() != ACCT_H2 {
            return Err(format!("w2/b2/w3 len != {ACCT_H2}"));
        }
        let mut out = AcctModel::analytical_default();
        out.w_acct.copy_from_slice(&j.w_acct);
        out.residual_scale = j.residual_scale;
        out.residual_active = j.residual_active;
        out.b1.copy_from_slice(&j.b1);
        out.b2.copy_from_slice(&j.b2);
        out.w3.copy_from_slice(&j.w3);
        for (i, row) in j.w1.iter().enumerate() {
            if row.len() != ACCT_FEAT_DIM {
                return Err(format!("w1[{i}] len {} != {ACCT_FEAT_DIM}", row.len()));
            }
            out.w1[i].copy_from_slice(row);
        }
        for (i, row) in j.w2.iter().enumerate() {
            if row.len() != ACCT_H1 {
                return Err(format!("w2[{i}] len {} != {ACCT_H1}", row.len()));
            }
            out.w2[i].copy_from_slice(row);
        }
        Ok(out)
    }
}

