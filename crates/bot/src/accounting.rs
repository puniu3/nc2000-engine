/// MobileNetV3 HardSwish activation: `x * clamp(x + 3, 0, 6) / 6`.
/// Smooth, non-monotonic like SiLU, zero `expf` transcendental calls, exact parity with
/// `torch.nn.functional.hardswish`.
#[inline(always)]
fn hardswish(x: f32) -> f32 {
    x * ((x + 3.0).clamp(0.0, 6.0) * (1.0 / 6.0))
}

/// Forward pass of the `48 -> 32 -> 16 -> 1` HardSwish residual MLP for one side.
#[inline]
pub fn acct_residual_forward(x: &[f32; ACCT_FEAT_DIM], m: &AcctModel) -> f32 {
    if !m.residual_active || m.residual_scale == 0.0 {
        return 0.0;
    }
    let mut h1 = [0.0f32; ACCT_H1];
    for i in 0..ACCT_H1 {
        let row = &m.w1[i];
        let mut s0 = m.b1[i];
        let mut s1 = 0.0f32;
        let mut s2 = 0.0f32;
        let mut s3 = 0.0f32;
        let mut j = 0;
        while j < ACCT_FEAT_DIM {
            s0 += row[j] * x[j];
            s1 += row[j + 1] * x[j + 1];
            s2 += row[j + 2] * x[j + 2];
            s3 += row[j + 3] * x[j + 3];
            j += 4;
        }
        h1[i] = hardswish((s0 + s1) + (s2 + s3));
    }

    let mut out = 0.0f32;
    for i in 0..ACCT_H2 {
        let row = &m.w2[i];
        let mut s0 = m.b2[i];
        let mut s1 = 0.0f32;
        let mut s2 = 0.0f32;
        let mut s3 = 0.0f32;
        let mut j = 0;
        while j < ACCT_H1 {
            s0 += row[j] * h1[j];
            s1 += row[j + 1] * h1[j + 1];
            s2 += row[j + 2] * h1[j + 2];
            s3 += row[j + 3] * h1[j + 3];
            j += 4;
        }
        let act = hardswish((s0 + s1) + (s2 + s3));
        out += m.w3[i] * act;
    }
    out
}

