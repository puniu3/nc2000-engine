/// Smooth pairwise duel valuation in `[-1.0, 1.0]` from `(s0, slot0)`'s perspective
/// against `(s1, slot1)`, incorporating entry Spikes HP loss (`hp_left`), switch-in
/// tempo delay (`extra`), heal-cycle walling, Substitute hit buffer, sleep/freeze
/// downtime (waived by Sleep Talk), confusion offense drop, and smooth 8-turn horizon.
#[allow(clippy::too_many_arguments)]
#[inline]
fn accounting_pair_margin(
    cb: &CompactBattle,
    table: &MatchTable,
    s0: usize,
    slot0: usize,
    s1: usize,
    slot1: usize,
    hp_left: [f64; 2],
    extra: [f64; 2],
) -> (f64, bool, bool) {
    let idx0 = s0 * 3 + slot0;
    let idx1 = s1 * 3 + slot1;
    let p0 = &cb.mons[idx0];
    let p1 = &cb.mons[idx1];
    if p0.hp() <= 0 || p1.hp() <= 0 {
        return (0.0, false, false);
    }
    match (hp_left[0] <= 0.0, hp_left[1] <= 0.0) {
        (true, true) => return (0.0, false, false),
        (true, false) => return (-1.0, false, false),
        (false, true) => return (1.0, false, false),
        _ => {}
    }

    let spd0 = cb.mon_action_speed(table, s0, slot0);
    let spd1 = cb.mon_action_speed(table, s1, slot1);

    let turns_and_walled = |att_s: usize,
                            att_slot: usize,
                            def_s: usize,
                            def_slot: usize,
                            att_faster: bool,
                            def_left: f64,
                            att_extra: f64|
     -> (f64, bool) {
        let att_idx = att_s * 3 + att_slot;
        let def_idx = def_s * 3 + def_slot;
        let att_mon = &cb.mons[att_idx];
        let def_mon = &cb.mons[def_idx];
        let def_spec = &table.mons[def_idx];
        let mut e = if def_mon.boosts[6] > 0 || att_mon.boosts[5] < 0 {
            let att_spec = &table.mons[att_idx];
            let dis = (att_mon.vol_flags & vol_bit::DISABLE) != 0;
            let dis_s = ((att_mon.slot_refs >> 4) & 0x03) as usize;
            let mut best = 0.0f64;
            for m_i in 0..att_spec.num_moves as usize {
                if att_mon.pp[m_i] == 0 || (dis && m_i == dis_s) {
                    continue;
                }
                let raw = cb.expected_hit_fraction(table, att_s, att_slot, def_s, def_slot, m_i, true);
                if raw <= 0.0 {
                    continue;
                }
                let p_hit = cb
                    .hit_probability(table, att_s, att_slot, def_s, def_slot, m_i)
                    .clamp(0.05, 1.0);
                let capped = (raw / p_hit).min(1.05) * p_hit;
                if capped > best {
                    best = capped;
                }
            }
            best
        } else {
            cb.best_hit_fraction(table, att_s, att_slot, def_s, def_slot, true)
        };
        if (att_mon.vol_flags & vol_bit::CONFUSION) != 0 && att_mon.timers[0] > 1 {
            e *= 0.55;
        }
        // Account for defender Leftovers passive regen (~1/16 maxHP per turn)
        let def_maxhp = def_spec.maxhp.max(1) as f64;
        let lefties_regen_rel = if def_mon.item != 0 && def_spec.is_leftovers {
            (def_spec.quantum_1_16.max(1) as f64) / (def_mon.hp().max(1) as f64)
        } else {
            0.0
        };
        let net_e = e - lefties_regen_rel;
        if e <= 1e-9 || net_e <= 0.02 {
            return (f64::INFINITY, true);
        }

        let def_dis = (def_mon.vol_flags & vol_bit::DISABLE) != 0;
        let def_dis_slot = ((def_mon.slot_refs >> 4) & 0x03) as usize;
        let mut has_heal = false;
        for m_i in 0..def_spec.num_moves as usize {
            if def_mon.pp[m_i] > 0
                && !(def_dis && m_i == def_dis_slot)
                && table.move_specs[def_idx][m_i].is_heal_cycle
            {
                has_heal = true;
                break;
            }
        }
        if has_heal {
            let dmg_frac_max = e * (def_mon.hp() as f64) / def_maxhp;
            let kill_now = e >= def_left && (att_faster || att_extra == 0.0 && def_left <= 0.5 * e);
            if dmg_frac_max < 0.48 && !kill_now {
                return (f64::INFINITY, true);
            }
        }

        let eff_rate = if e >= def_left { e } else { net_e.max(0.05) };
        let mut t = (def_left / eff_rate).ceil() + att_extra;
        if (def_mon.vol_flags & vol_bit::SUBSTITUTE) != 0 && (def_slot as u8) == cb.sides[def_s].active_idx {
            t += 1.0;
        }
        if (att_mon.slot_refs & 0x80) != 0 && (att_slot as u8) == cb.sides[att_s].active_idx {
            t += 1.0;
        }
        let st_raw = att_mon.status_raw();
        if st_raw == Status::Slp as u8 {
            let att_spec = &table.mons[att_idx];
            let mut talks = false;
            for m_i in 0..att_spec.num_moves as usize {
                if att_mon.pp[m_i] > 0 && table.move_specs[att_idx][m_i].special_kind == 10 {
                    talks = true;
                    break;
                }
            }
            if !talks && !(att_mon.item != 0 && (att_spec.is_mintberry || att_spec.is_miracleberry)) {
                t += att_mon.status_counter().clamp(1, 4) as f64;
            }
        } else if st_raw == Status::Frz as u8
            && !(att_mon.item != 0 && table.mons[att_idx].is_miracleberry)
        {
            t += 4.0;
        }
        (t, false)
    };

    let surv = |s: usize, slot: usize, left: f64| -> f64 {
        let idx = s * 3 + slot;
        let p = &cb.mons[idx];
        let spec = &table.mons[idx];
        let st = p.status_raw();
        if st != Status::Psn as u8 && st != Status::Tox as u8 && st != Status::Brn as u8 {
            return f64::INFINITY;
        }
        let hp = (p.hp() as f64) * left;
        let cnt_packed = p.status_counter();
        if (slot as u8) == cb.sides[s].active_idx && (st == Status::Tox as u8 || (cnt_packed & 0x10) != 0) {
            let c = (cnt_packed & 0x0F) as i64;
            let unit = (spec.maxhp as f64 / 16.0).floor().max(1.0);
            let mut acc = 0.0;
            for k in 1..=10u32 {
                acc += unit * (c + k as i64).max(1) as f64;
                if acc >= hp {
                    return k as f64;
                }
            }
            f64::INFINITY
        } else {
            let tick = (spec.maxhp as f64 / 8.0).floor().max(1.0);
            (hp / tick).ceil()
        }
    };

    let (k0, walled_by_1) = turns_and_walled(s0, slot0, s1, slot1, spd0 > spd1, hp_left[1], extra[0]);
    let (k1, walled_by_0) = turns_and_walled(s1, slot1, s0, slot0, spd1 > spd0, hp_left[0], extra[1]);
    let (v0, v1) = (surv(s0, slot0, hp_left[0]), surv(s1, slot1, hp_left[1]));
    let k0 = if k0 <= v0 { k0 } else { f64::INFINITY };
    let k1 = if k1 <= v1 { k1 } else { f64::INFINITY };
    let t0 = k0.min(v1);
    let t1 = k1.min(v0);

    if !t0.is_finite() && !t1.is_finite() {
        return (0.0, walled_by_0, walled_by_1);
    }
    if t0.min(t1) > 8.0 {
        return (0.0, walled_by_0, walled_by_1);
    }
    let val = match (t0.is_finite(), t1.is_finite()) {
        (true, false) => (1.15 - 0.08 * (t0 - 1.0).max(0.0)).clamp(0.35, 1.0),
        (false, true) => -(1.15 - 0.08 * (t1 - 1.0).max(0.0)).clamp(0.35, 1.0),
        (true, true) => {
            let edge = match spd0.cmp(&spd1) {
                std::cmp::Ordering::Greater => 0.45,
                std::cmp::Ordering::Less => -0.45,
                std::cmp::Ordering::Equal => 0.0,
            };
            (0.55 * ((t1 - t0) + edge)).tanh()
        }
        (false, false) => 0.0,
    };
    (val.clamp(-1.0, 1.0), walled_by_0, walled_by_1)
}

#[derive(Clone, Copy)]
struct SideSummary {
    ledger: [f64; ACCT_BASIS_DIM],
    feat: [f32; ACCT_FEAT_DIM],
}

/// Extract the complete double-entry accounting basis differential `basis_diff`
/// (`side 0 - side 1`) and exact mirror-symmetric per-side feature vectors `(feat0, feat1)`.
///
/// Algebraic Symmetry Guarantee:
/// On `(swapped_cb, swapped_table) = swap_compact_sides(cb, table)`:
/// - `basis_diff(swapped)` == `-basis_diff(original)`
/// - `feat0(swapped)` == `feat1(original)` and `feat1(swapped)` == `feat0(original)`!
#[inline]
pub fn extract_acct_components(
    cb: &CompactBattle,
    table: &MatchTable,
    w_acct: &[f32; ACCT_BASIS_DIM],
) -> ([f32; ACCT_BASIS_DIM], [f32; ACCT_FEAT_DIM], [f32; ACCT_FEAT_DIM]) {
    let n0 = cb.sides[0].alive_mask.count_ones();
    let n1 = cb.sides[1].alive_mask.count_ones();
    if n0 == 0 || n1 == 0 {
        return ([0.0; ACCT_BASIS_DIM], [0.0; ACCT_FEAT_DIM], [0.0; ACCT_FEAT_DIM]);
    }

    let flying_mask = 1u32 << (table.flying_type & 31);
    let ghost_mask = 1u32 << (table.ghost_type & 31);

    let entry_left = |s: usize, slot: usize| -> f64 {
        if (slot as u8) == cb.sides[s].active_idx {
            return 1.0;
        }
        let idx = s * 3 + slot;
        if (table.mons[idx].type_mask & flying_mask) != 0 {
            return 1.0;
        }
        let layers = (cb.sides[s].side_flags & 0x03) as usize;
        if layers == 0 {
            return 1.0;
        }
        const AMOUNTS: [f64; 4] = [0.0, 3.0, 4.0, 6.0];
        let dmg = (AMOUNTS[layers] * (table.mons[idx].maxhp as f64) / 24.0)
            .floor()
            .max(1.0);
        1.0 - dmg / (cb.mons[idx].hp().max(1) as f64)
    };

    // Compute all alive pair margins ONCE (`ko * kf` pairs instead of `2 * ko * kf`)
    // since `accounting_pair_margin` is algebraically skew-symmetric (`mat1[j][i] == -mat0[i][j]`).
    let mut slots0 = [0usize; 3];
    let mut k0 = 0usize;
    let mut slots1 = [0usize; 3];
    let mut k1 = 0usize;
    let mut act_i0 = 0usize;
    let mut act_i1 = 0usize;
    for slot in 0..3usize {
        if (cb.sides[0].alive_mask & (1 << slot)) != 0 && cb.mons[slot].hp() > 0 {
            if slot as u8 == cb.sides[0].active_idx {
                act_i0 = k0;
            }
            slots0[k0] = slot;
            k0 += 1;
        }
        if (cb.sides[1].alive_mask & (1 << slot)) != 0 && cb.mons[3 + slot].hp() > 0 {
            if slot as u8 == cb.sides[1].active_idx {
                act_i1 = k1;
            }
            slots1[k1] = slot;
            k1 += 1;
        }
    }

    let mut mat0 = [[0.0f64; 4]; 4];
    let mut mat1 = [[0.0f64; 4]; 4];
    let mut walls0 = [false; 3];
    let mut walls1 = [false; 3];
    for i in 0..k0 {
        let a = slots0[i];
        let la = entry_left(0, a);
        let ea = if (a as u8) != cb.sides[0].active_idx { 1.0 } else { 0.0 };
        for j in 0..k1 {
            let d = slots1[j];
            let ld = entry_left(1, d);
            let ed = if (d as u8) != cb.sides[1].active_idx { 1.0 } else { 0.0 };
            let (v, w_by_0, w_by_1) =
                accounting_pair_margin(cb, table, 0, a, 1, d, [la, ld], [ea, ed]);
            mat0[i][j] = v;
            mat1[j][i] = -v;
            if w_by_0 {
                walls0[i] = true;
            }
            if w_by_1 {
                walls1[j] = true;
            }
        }
    }

    let summarize_matchup = |ko: usize,
                             kf: usize,
                             own_slots: [usize; 3],
                             foe_slots: [usize; 3],
                             mat: [[f64; 4]; 4],
                             walls: [bool; 3],
                             own_act_i: usize,
                             foe_act_j: usize|
     -> (
        usize,
        usize,
        [usize; 3],
        [usize; 3],
        [[f64; 4]; 4],
        f64,
        f64,
        f64,
        f64,
        f64,
        f64,
        f64,
        f64,
    ) {
        let mut heal_walls = 0u32;
        for &w in &walls[..ko] {
            if w {
                heal_walls += 1;
            }
        }
        let (v_nash, _, _) = solve_stage_matrix_rm_plus_4(&mat, ko, kf, 24);
        let mut maximin = f64::NEG_INFINITY;
        for i in 0..ko {
            let mut rmin = f64::INFINITY;
            for j in 0..kf {
                if mat[i][j] < rmin {
                    rmin = mat[i][j];
                }
            }
            if rmin > maximin {
                maximin = rmin;
            }
        }
        let mut minimax = f64::INFINITY;
        for j in 0..kf {
            let mut cmax = f64::NEG_INFINITY;
            for i in 0..ko {
                if mat[i][j] > cmax {
                    cmax = mat[i][j];
                }
            }
            if cmax < minimax {
                minimax = cmax;
            }
        }
        let m_active = mat[own_act_i][foe_act_j];
        let mut best_bench_vs_foe_act = -1.0f64;
        let mut max_vs_foe_act = -1.0f64;
        for i in 0..ko {
            let v = mat[i][foe_act_j];
            if v > max_vs_foe_act {
                max_vs_foe_act = v;
            }
            if i != own_act_i && v > best_bench_vs_foe_act {
                best_bench_vs_foe_act = v;
            }
        }
        if ko <= 1 {
            best_bench_vs_foe_act = m_active;
        }
        let heal_wall_frac = (heal_walls as f64) / 3.0;
        (
            ko,
            kf,
            own_slots,
            foe_slots,
            mat,
            v_nash,
            maximin,
            minimax,
            m_active,
            best_bench_vs_foe_act,
            max_vs_foe_act,
            heal_wall_frac,
            own_act_i as f64,
        )
    };

    let m0 = summarize_matchup(k0, k1, slots0, slots1, mat0, walls0, act_i0, act_i1);
    let m1 = summarize_matchup(k1, k0, slots1, slots0, mat1, walls1, act_i1, act_i0);

    // Exact linear endgame & Perish term (`compact_linear_diff` is already strictly
    // antisymmetric and hits `MatchTable`'s thread-local Toeplitz cache directly!).
    let s0_act = (cb.sides[0].active_idx as usize).min(2);
    let s1_act = (cb.sides[1].active_idx as usize).min(2);
    let has_perish = ((cb.mons[s0_act].vol_flags | cb.mons[3 + s1_act].vol_flags)
        & vol_bit::PERISH_SONG)
        != 0;
    let sym_lin0 = if (n0 + n1) <= 3 || has_perish {
        crate::linear::compact_linear_diff(cb, table, 0.0, 0.0, 5.3, 1.0)
    } else {
        0.0
    };
    let toeplitz_1v1_liquidated = n0 == 1 && n1 == 1 && !has_perish && sym_lin0 != 0.0;

    let build_side = |s: usize,
                      m_own: &(
                          usize,
                          usize,
                          [usize; 3],
                          [usize; 3],
                          [[f64; 4]; 4],
                          f64,
                          f64,
                          f64,
                          f64,
                          f64,
                          f64,
                          f64,
                          f64,
                      ),
                      lin_signed: f64|
     -> SideSummary {
        let foe = 1 - s;
        let side_st = &cb.sides[s];
        let foe_st = &cb.sides[foe];
        let act_slot = (side_st.active_idx as usize).min(2);
        let foe_act_slot = (foe_st.active_idx as usize).min(2);
        let act_idx = s * 3 + act_slot;
        let foe_act_idx = foe * 3 + foe_act_slot;

        // Check party-wide Heal Bell & Phaze availability.
        let mut party_has_heal_bell = false;
        let mut party_has_phaze = false;
        let mut foe_has_phaze = false;
        let mut foe_act_has_phaze = false;
        let mut own_heal_cnt = 0.0f32;
        let mut own_rest_talk_cnt = 0.0f32;
        let mut own_lefties_cnt = 0.0f32;

        for slot in 0..3usize {
            if (side_st.alive_mask & (1 << slot)) != 0 && cb.mons[s * 3 + slot].hp() > 0 {
                let idx = s * 3 + slot;
                let mon = &cb.mons[idx];
                let spec = &table.mons[idx];
                if mon.item != 0 && spec.is_leftovers {
                    own_lefties_cnt += 1.0;
                }
                let dis = (mon.vol_flags & vol_bit::DISABLE) != 0;
                let dis_s = ((mon.slot_refs >> 4) & 0x03) as usize;
                let mut has_rest = false;
                let mut has_talk = false;
                let mut has_heal = false;
                for m_i in 0..spec.num_moves as usize {
                    if mon.pp[m_i] == 0 || (dis && m_i == dis_s) {
                        continue;
                    }
                    let ms = &table.move_specs[idx][m_i];
                    if ms.special_kind == 21 {
                        party_has_heal_bell = true;
                    }
                    if ms.special_kind == 7 || ms.special_kind == 27 {
                        party_has_phaze = true;
                    }
                    if ms.is_heal_cycle {
                        has_heal = true;
                    }
                    if ms.is_rest {
                        has_rest = true;
                    }
                    if ms.special_kind == 10 {
                        has_talk = true;
                    }
                }
                if has_heal {
                    own_heal_cnt += 1.0;
                }
                if has_rest && has_talk {
                    own_rest_talk_cnt += 1.0;
                }
            }
            if (foe_st.alive_mask & (1 << slot)) != 0 && cb.mons[foe * 3 + slot].hp() > 0 {
                let fidx = foe * 3 + slot;
                let fmon = &cb.mons[fidx];
                let fspec = &table.mons[fidx];
                let fdis = (fmon.vol_flags & vol_bit::DISABLE) != 0;
                let fdis_s = ((fmon.slot_refs >> 4) & 0x03) as usize;
                for m_i in 0..fspec.num_moves as usize {
                    if fmon.pp[m_i] == 0 || (fdis && m_i == fdis_s) {
                        continue;
                    }
                    let ms = &table.move_specs[fidx][m_i];
                    if (ms.special_kind == 7 && side_st.alive_mask.count_ones() > 1)
                        || ms.special_kind == 27
                    {
                        foe_has_phaze = true;
                        if slot == foe_act_slot {
                            foe_act_has_phaze = true;
                        }
                    }
                }
            }
        }

        let spk_layers = (side_st.side_flags & 0x03) as usize;
        const SPK_AMOUNTS: [f64; 4] = [0.0, 3.0, 4.0, 6.0];
        let spk_frac = SPK_AMOUNTS[spk_layers] / 24.0;

        let mut alive_net = 0.0f64;
        let mut hp_net = 0.0f64;
        let mut item_cap = 0.0f64;
        let mut status_imp = 0.0f64;
        let mut grounded_bench = 0.0f64;
        let mut dead_on_spikes_cnt = 0.0f32;
        let mut pp_num = 0.0f64;
        let mut pp_den = 0.0f64;
        let mut bench_hp_sum = 0.0f32;
        let mut bench_hp_max = 0.0f32;
        let mut best_receiver_fit = 0.0f64;

        for slot in 0..3usize {
            if (side_st.alive_mask & (1 << slot)) == 0 {
                continue;
            }
            let idx = s * 3 + slot;
            let mon = &cb.mons[idx];
            let spec = &table.mons[idx];
            let hp = mon.hp();
            if hp <= 0 {
                continue;
            }
            let maxhp = spec.maxhp.max(1) as f64;
            let is_bench = slot != act_slot;
            let is_grounded = (spec.type_mask & flying_mask) == 0;

            let (eff_hp, eff_alive_unit) = if is_bench && is_grounded && spk_layers > 0 {
                grounded_bench += 1.0;
                let spk_dmg = (SPK_AMOUNTS[spk_layers] * maxhp / 24.0).floor().max(1.0);
                if (hp as f64) <= spk_dmg {
                    dead_on_spikes_cnt += 1.0;
                    (0.0, 0.15)
                } else {
                    (((hp as f64) - spk_dmg) / maxhp, 1.0)
                }
            } else {
                if is_bench && is_grounded {
                    grounded_bench += 1.0;
                }
                ((hp as f64) / maxhp, 1.0)
            };

            alive_net += eff_alive_unit;
            hp_net += eff_hp;
            if is_bench {
                bench_hp_sum += eff_hp as f32;
                if (eff_hp as f32) > bench_hp_max {
                    bench_hp_max = eff_hp as f32;
                }
                let off_stat = spec.stored_stats[0].max(spec.stored_stats[2]) as f64 / 200.0;
                let fit = eff_hp * off_stat.clamp(0.4, 1.5);
                if fit > best_receiver_fit {
                    best_receiver_fit = fit;
                }
            }

            // Held item capital
            if mon.item != 0 {
                if spec.is_leftovers {
                    item_cap += 0.35 * eff_hp.max(0.05).sqrt();
                } else if spec.is_goldberry {
                    item_cap += (30.0 / maxhp).min(0.30);
                } else if spec.is_berry {
                    item_cap += (10.0 / maxhp).min(0.12);
                } else if spec.is_miracleberry {
                    item_cap += 0.22;
                } else if spec.is_mintberry {
                    item_cap += 0.15;
                } else if spec.is_mysteryberry {
                    item_cap += 0.08;
                }
            }

            // Inspect moves for physical/special kit & Sleep Talk
            let mut has_phys_atk = false;
            let mut has_sleep_talk = false;
            for m_i in 0..spec.num_moves as usize {
                let p = mon.pp[m_i];
                pp_num += p as f64;
                pp_den += spec.max_pp[m_i] as f64;
                if p == 0 {
                    continue;
                }
                let ms = &table.move_specs[idx][m_i];
                if !ms.is_status && ms.is_physical && !ms.is_selfdestruct && (ms.base_power > 0 || ms.var_bp_kind != 0) {
                    has_phys_atk = true;
                }
                if ms.special_kind == 10 {
                    has_sleep_talk = true;
                }
            }

            // Status impairment (adjusted for physical/special Burn, Sleep Talk, and party Heal Bell)
            let st_raw = mon.status_raw();
            let mut raw_st_cost = if st_raw == Status::Brn as u8 {
                if has_phys_atk { 0.42 } else { 0.20 }
            } else if st_raw == Status::Par as u8 {
                0.36
            } else if st_raw == Status::Slp as u8 {
                let t = mon.status_counter().clamp(0, 4) as f64 / 3.0;
                let base_slp = 0.44 * t;
                if has_sleep_talk { 0.35 * base_slp } else { base_slp }
            } else if st_raw == Status::Frz as u8 {
                0.58
            } else if st_raw == Status::Psn as u8 {
                0.24
            } else if st_raw == Status::Tox as u8 {
                if !is_bench {
                    let c = (mon.status_counter() & 0x0F) as f64;
                    0.30 + 0.05 * c
                } else {
                    0.24
                }
            } else {
                0.0
            };
            if is_bench && party_has_heal_bell {
                raw_st_cost *= 0.55;
            }
            status_imp += raw_st_cost;
        }

        let mut foe_bench_hp_sum = 0.0f32;
        for slot in 0..3usize {
            if slot != foe_act_slot
                && (foe_st.alive_mask & (1 << slot)) != 0
                && cb.mons[foe * 3 + slot].hp() > 0
            {
                let fidx = foe * 3 + slot;
                foe_bench_hp_sum +=
                    (cb.mons[fidx].hp() as f32) / (table.mons[fidx].maxhp.max(1) as f32);
            }
        }

        let act_mon = &cb.mons[act_idx];
        let act_spec = &table.mons[act_idx];
        let foe_act_mon = &cb.mons[foe_act_idx];
        let foe_act_spec = &table.mons[foe_act_idx];
        let act_alive = (side_st.alive_mask & (1 << act_slot)) != 0 && act_mon.hp() > 0;
        let foe_act_alive =
            (foe_st.alive_mask & (1 << foe_act_slot)) != 0 && foe_act_mon.hp() > 0;

        let act_hp_frac = if act_alive {
            (act_mon.hp() as f32) / (act_spec.maxhp.max(1) as f32)
        } else {
            0.0
        };
        let foe_act_hp_frac = if foe_act_alive {
            (foe_act_mon.hp() as f32) / (foe_act_spec.maxhp.max(1) as f32)
        } else {
            0.0
        };

        let sub_hp_frac = if act_alive && (act_mon.vol_flags & vol_bit::SUBSTITUTE) != 0 {
            (act_mon.sub_hp().max(0) as f32) / (act_spec.maxhp.max(1) as f32)
        } else {
            0.0
        };
        let foe_sub_hp_frac = if foe_act_alive && (foe_act_mon.vol_flags & vol_bit::SUBSTITUTE) != 0
        {
            (foe_act_mon.sub_hp().max(0) as f32) / (foe_act_spec.maxhp.max(1) as f32)
        } else {
            0.0
        };
        let sub_present = if sub_hp_frac > 0.0 { 1.0f64 } else { 0.0 };
        let sub_capital = 1.6 * (sub_hp_frac as f64) + 0.35 * sub_present;

        // Active volatile drain liabilities
        let mut vol_drain = 0.0f64;
        if act_alive {
            if (act_mon.vol_flags & vol_bit::LEECH_SEED) != 0 {
                vol_drain += 0.28;
            }
            if (act_mon.vol_flags & vol_bit::CURSE) != 0 {
                vol_drain += 0.36;
            }
            if (act_mon.vol_flags & vol_bit::NIGHTMARE) != 0 && act_mon.status_raw() == Status::Slp as u8 {
                vol_drain += 0.30;
            }
            if (act_mon.vol_flags & vol_bit::CONFUSION) != 0 {
                let att = (act_mon.timers[0].clamp(0, 5) as f64 - 1.0).max(0.0);
                vol_drain += 0.16 * 0.5 * att;
            }
            if (act_mon.vol_flags & vol_bit::ENCORE) != 0 {
                vol_drain += 0.22;
            }
            if (act_mon.vol_flags & vol_bit::DISABLE) != 0 {
                vol_drain += 0.14;
            }
        }

        let screens_cap = ((side_st.reflect_turns.min(5) as f64)
            + (side_st.lightscreen_turns.min(5) as f64)
            + 0.7 * (side_st.safeguard_turns.min(5) as f64))
            / 5.0;
        let spikes_repeat_neg = -grounded_bench * spk_frac;
        let pp_cap = if pp_den > 0.0 { pp_num / pp_den } else { 0.0 };

        // Active move kit scan
        let mut act_has_phys = false;
        let mut act_has_spec = false;
        let mut act_has_bp = false;
        let mut act_has_setup = false;
        let mut act_has_heal = false;
        let mut act_has_sleep_mv = false;
        let mut act_has_prio = act_mon.item != 0 && act_spec.is_quick_claw;
        let mut act_has_boom = false;
        let mut act_has_dbond_cnt = false;

        if act_alive {
            let dis = (act_mon.vol_flags & vol_bit::DISABLE) != 0;
            let dis_s = ((act_mon.slot_refs >> 4) & 0x03) as usize;
            let foe_is_ghost = foe_act_alive && (foe_act_spec.type_mask & ghost_mask) != 0;
            for m_i in 0..act_spec.num_moves as usize {
                if act_mon.pp[m_i] == 0 || (dis && m_i == dis_s) {
                    continue;
                }
                let ms = &table.move_specs[act_idx][m_i];
                if !ms.is_status && (ms.base_power > 0 || ms.var_bp_kind != 0) {
                    if ms.is_physical && !ms.is_selfdestruct {
                        act_has_phys = true;
                    } else if !ms.is_physical {
                        act_has_spec = true;
                    }
                }
                if ms.priority > 0 {
                    act_has_prio = true;
                }
                if ms.is_selfdestruct && side_st.alive_mask.count_ones() > 1 && !foe_is_ghost {
                    act_has_boom = true;
                }
                if ms.special_kind == 18 && side_st.alive_mask.count_ones() > 1 {
                    act_has_bp = true;
                }
                if ms.boosts_self || matches!(ms.pseudo_kind, 5..=8) {
                    act_has_setup = true;
                }
                if ms.is_heal_cycle {
                    act_has_heal = true;
                }
                if ms.primary_status == Status::Slp as u8 {
                    act_has_sleep_mv = true;
                }
                if matches!(ms.special_kind, 11 | 12 | 20) {
                    act_has_dbond_cnt = true;
                }
            }
        }

        // Verified boosts & Baton Pass capital
        let mut boost_off = 0.0f64;
        let mut boost_def_spe_eva = 0.0f64;
        let mut pos_off_b = 0.0f32;
        let mut pos_def_b = 0.0f32;
        let mut pos_spe_eva_b = 0.0f32;
        let mut neg_b_load = 0.0f32;
        let mut foe_pos_b = 0.0f32;

        if act_alive {
            let b = &act_mon.boosts;
            if act_has_phys || act_has_bp || b[0] < 0 {
                boost_off += ((b[0] as f64) / 3.0).tanh() * 0.55;
            }
            if act_has_spec || act_has_bp || b[2] < 0 {
                boost_off += ((b[2] as f64) / 3.0).tanh() * 0.55;
            }
            boost_def_spe_eva += ((b[1] as f64) / 3.0).tanh() * 0.32
                + ((b[3] as f64) / 3.0).tanh() * 0.32
                + ((b[4] as f64) / 3.0).tanh() * 0.48
                + ((b[5] as f64) / 3.0).tanh() * 0.25
                + ((b[6] as f64) / 3.0).tanh() * 0.42;

            // Stacked Evasion-Wall capital (`b[6] >= 2`): in Gen 2, +2..=+6 evasion multiplies
            // expected durability up to 3.0x (`256/84`), compounding multiplicatively with
            // offensive setup / recovery and becoming nearly unbreakable if the opponent has
            // no active phazer on the field (`!foe_act_has_phaze`) or alive (`!foe_has_phaze`).
            if b[6] >= 2 {
                let eva_excess = (b[6] - 1) as f64;
                let off_syn = 1.0
                    + 0.25 * (b[0].max(b[2]).max(0) as f64).min(4.0)
                    + if act_has_heal { 0.35 } else { 0.0 };
                let phaze_mult = if !foe_has_phaze {
                    1.25
                } else if !foe_act_has_phaze {
                    1.00
                } else {
                    0.55
                };
                boost_def_spe_eva += 0.55 * eva_excess * (act_hp_frac as f64) * off_syn * phaze_mult;
            }

            pos_off_b = (b[0].max(b[2]).max(0) as f32) / 4.0;
            pos_def_b = ((b[1].max(0) + b[3].max(0)) as f32) / 6.0;
            pos_spe_eva_b = ((b[4].max(0) as f32) + 1.5 * (b[6].max(0) as f32)) / 6.0;
            for &bi in b.iter() {
                if bi < 0 {
                    neg_b_load += (-bi as f32) / 6.0;
                }
            }
        }
        if foe_act_alive {
            for &bi in foe_act_mon.boosts.iter() {
                if bi > 0 {
                    foe_pos_b += (bi as f32) / 6.0;
                }
            }
        }

        let (act_eff, foe_act_eff, faster) = if act_alive && foe_act_alive {
            let e_own = cb.best_hit_fraction(table, s, act_slot, foe, foe_act_slot, true);
            let e_foe = cb.best_hit_fraction(table, foe, foe_act_slot, s, act_slot, true);
            let spd_o = cb.mon_action_speed(table, s, act_slot);
            let spd_f = cb.mon_action_speed(table, foe, foe_act_slot);
            let fst = match spd_o.cmp(&spd_f) {
                std::cmp::Ordering::Greater => 1.0f32,
                std::cmp::Ordering::Less => -1.0f32,
                std::cmp::Ordering::Equal => 0.0f32,
            };
            (e_own, e_foe, fst)
        } else {
            (0.0, 0.0, 0.0)
        };

        // Initiative-adjusted active threat tempo: if slower and about to be OHKO'd without Sub,
        // our active threat cannot execute!
        let slower_dying = faster < 0.0 && foe_act_eff >= 0.98 && sub_present == 0.0;
        let tempo_mult = if slower_dying {
            0.22
        } else if faster > 0.0 && act_eff >= 0.98 {
            1.25
        } else {
            0.85
        };
        let active_tempo = tempo_mult * act_eff.min(1.25);

        let v_nash = m_own.5;
        let maximin = m_own.6;
        let minimax = m_own.7;
        let m_active = m_own.8;
        let best_bench_vs_foe = m_own.9;
        let max_vs_foe_act = m_own.10;
        let heal_wall_frac = m_own.11;

        let multi_active = (n0 + n1) >= 4;
        let matchup_multi = if multi_active { 0.5 * v_nash } else { 0.0 };
        let switch_pivot = if side_st.alive_mask.count_ones() >= 2 {
            (best_bench_vs_foe - m_active).max(0.0)
        } else {
            0.0
        };
        // Divide symmetric linear diff by 2 per side so `ledger0[14] - ledger1[14] == sym_lin0`.
        let endgame_lin_half = 0.5 * lin_signed;

        let passable_stock =
            (pos_off_b as f64) + 0.7 * (pos_def_b as f64) + 0.8 * (pos_spe_eva_b as f64) + 0.5 * sub_present;
        let phaze_disc = if foe_has_phaze { 0.45 } else { 1.0 };
        let bp_synergy = if act_has_bp {
            passable_stock.min(2.0) * best_receiver_fit.clamp(0.25, 1.3) * phaze_disc
        } else {
            0.0
        };

        // Double-entry non-double-counting invariant:
        // When `toeplitz_1v1_liquidated` holds (`n0 == 1 && n1 == 1`), `sym_lin0` already
        // prices exact coupled Markov win log-odds over HP, Leftovers, status, speed, and damage!
        let non_1v1 = if toeplitz_1v1_liquidated { 0.0 } else { 1.0 };

        let ledger = [
            alive_net,
            non_1v1 * hp_net,
            sub_capital,
            non_1v1 * item_cap,
            -non_1v1 * status_imp,
            -vol_drain,
            screens_cap,
            spikes_repeat_neg,
            pp_cap,
            non_1v1 * boost_off,
            non_1v1 * boost_def_spe_eva,
            non_1v1 * active_tempo,
            matchup_multi,
            switch_pivot,
            endgame_lin_half,
            bp_synergy,
        ];

        let mut side_logit_est = 0.0f32;
        for j in 0..ACCT_BASIS_DIM {
            side_logit_est += w_acct[j] * (ledger[j] as f32);
        }

        // Build 48-dimensional normalized synergy vector `feat`.
        let mut x = [0.0f32; ACCT_FEAT_DIM];
        let own_alive_cnt = side_st.alive_mask.count_ones() as f32;
        let foe_alive_cnt = foe_st.alive_mask.count_ones() as f32;
        x[0] = own_alive_cnt / 3.0;
        x[1] = foe_alive_cnt / 3.0;
        x[2] = act_hp_frac;
        x[3] = foe_act_hp_frac;
        x[4] = bench_hp_sum * 0.5;
        x[5] = bench_hp_max;
        x[6] = foe_bench_hp_sum * 0.5;
        x[7] = (sub_hp_frac * 4.0).min(1.2);
        x[8] = (foe_sub_hp_frac * 4.0).min(1.2);
        x[9] = dead_on_spikes_cnt * 0.5;

        let act_ko_now = ((act_eff as f32) - 0.70).clamp(0.0, 0.80);
        let foe_ko_now = ((foe_act_eff as f32) - 0.70).clamp(0.0, 0.80);
        x[10] = (act_eff as f32).min(1.5);
        x[11] = (foe_act_eff as f32).min(1.5);
        x[12] = faster;
        x[13] = act_ko_now;
        x[14] = foe_ko_now;
        x[15] = faster.max(0.0) * act_ko_now;
        x[16] = (-faster).max(0.0) * foe_ko_now * (1.0 - (sub_present as f32));
        x[17] = if act_has_prio { 1.0 } else { 0.0 };
        x[18] = if act_has_boom { 1.0 } else { 0.0 };
        x[19] = if act_has_dbond_cnt { 1.0 } else { 0.0 };

        x[20] = v_nash as f32;
        x[21] = maximin.clamp(-1.0, 1.0) as f32;
        x[22] = minimax.clamp(-1.0, 1.0) as f32;
        x[23] = (minimax - maximin).clamp(0.0, 2.0) as f32 * 0.5;
        x[24] = m_active as f32;
        x[25] = best_bench_vs_foe as f32;
        x[26] = switch_pivot as f32;
        x[27] = maximin.max(0.0) as f32;
        x[28] = (-max_vs_foe_act).max(0.0) as f32;
        x[29] = heal_wall_frac as f32;

        x[30] = pos_off_b.min(1.5);
        x[31] = pos_def_b.min(1.5);
        x[32] = pos_spe_eva_b.min(1.5);
        x[33] = neg_b_load.min(1.5);
        x[34] = if act_has_bp { 1.0 } else { 0.0 };
        x[35] = (bp_synergy as f32).min(2.0);
        x[36] = if act_has_setup { 1.0 } else { 0.0 };
        x[37] = if act_has_setup && !foe_has_phaze {
            (1.0 - foe_ko_now).max(0.0) * act_hp_frac
        } else {
            0.0
        };
        x[38] = if party_has_phaze { 1.0 } else { 0.0 };
        x[39] = if !party_has_phaze { foe_pos_b.min(1.5) } else { 0.0 };

        let foe_sleep_clause_locked = (cb.clause_flags & (1 << foe)) != 0;
        let sleep_open = act_has_sleep_mv
            && !foe_sleep_clause_locked
            && foe_act_alive
            && foe_act_mon.status_raw() == 0
            && foe_st.safeguard_turns == 0
            && foe_sub_hp_frac == 0.0;
        x[40] = own_heal_cnt / 3.0;
        x[41] = own_rest_talk_cnt * 0.5;
        x[42] = own_lefties_cnt / 3.0;
        x[43] = (-spikes_repeat_neg as f32).min(1.0);
        x[44] = (screens_cap as f32).min(1.5);
        x[45] = (vol_drain as f32 + status_imp as f32 * 0.5).min(1.5);
        x[46] = if sleep_open { 1.0 } else { 0.0 };
        x[47] = (side_logit_est / 3.0).tanh();

        SideSummary { ledger, feat: x }
    };

    let s0 = build_side(0, &m0, sym_lin0);
    let s1 = build_side(1, &m1, -sym_lin0);

    let mut basis_diff = [0.0f32; ACCT_BASIS_DIM];
    for j in 0..ACCT_BASIS_DIM {
        basis_diff[j] = (s0.ledger[j] - s1.ledger[j]) as f32;
    }
    // Re-center `feat[47]` on the true antisymmetric differential logit so `feat0` and `feat1`
    // share exact contextual magnitude while preserving `feat0(swap) == feat1(orig)`.
    let mut diff_logit = 0.0f32;
    for j in 0..ACCT_BASIS_DIM {
        diff_logit += w_acct[j] * basis_diff[j];
    }
    let mut f0 = s0.feat;
    let mut f1 = s1.feat;
    f0[47] = (diff_logit / 3.0).tanh();
    f1[47] = (-diff_logit / 3.0).tanh();

    (basis_diff, f0, f1)
}

/// Evaluate quiescent board equity $E(cb) = \sigma(L_{\text{acct}}(cb) + \Delta_{\text{sym}}(cb)) \in [0, 1]$
/// using explicit `model`. Strictly antisymmetric: `E(cb) + E(swap(cb)) == 1.0`.
#[inline]
pub fn compact_accounting_equity_with_model(
    cb: &CompactBattle,
    table: &MatchTable,
    model: &AcctModel,
) -> f64 {
    match cb.outcome {
        1 => return 1.0,
        2 => return 0.0,
        3 => return 0.5,
        _ => {}
    }
    let a0 = cb.sides[0].alive_mask;
    let a1 = cb.sides[1].alive_mask;
    match (a0 == 0, a1 == 0) {
        (true, true) => return 0.5,
        (true, false) => return 0.0,
        (false, true) => return 1.0,
        (false, false) => {}
    }

    let (basis_diff, f0, f1) = extract_acct_components(cb, table, &model.w_acct);
    let mut logit = 0.0f64;
    for j in 0..ACCT_BASIS_DIM {
        logit += (model.w_acct[j] as f64) * (basis_diff[j] as f64);
    }
    if model.residual_active && model.residual_scale != 0.0 {
        let r0 = acct_residual_forward(&f0, model);
        let r1 = acct_residual_forward(&f1, model);
        logit += (model.residual_scale as f64) * ((r0 - r1) as f64);
    }
    1.0 / (1.0 + (-logit).exp())
}

/// Evaluate quiescent board equity using the active process/thread-local [`AcctModel`].
#[inline]
pub fn compact_accounting_equity(cb: &CompactBattle, table: &MatchTable) -> f64 {
    ACCT_CTX.with(|cell| {
        let mut ctx = cell.borrow_mut();
        ctx.ensure_fresh();
        compact_accounting_equity_with_model(cb, table, &ctx.model)
    })
}

