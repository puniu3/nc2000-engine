pub const DEFAULT_ACCT_MODEL: AcctModel = TRAINED_ACCT_MODEL;

static GLOBAL_MODEL_EPOCH: AtomicU64 = AtomicU64::new(1);
static GLOBAL_MODEL_STORE: Mutex<AcctModel> = Mutex::new(DEFAULT_ACCT_MODEL);

/// Install a new [`AcctModel`] process-wide and invalidate all thread-local leaf caches.
pub fn set_active_acct_model(model: AcctModel) {
    if let Ok(mut guard) = GLOBAL_MODEL_STORE.lock() {
        *guard = model;
    }
    GLOBAL_MODEL_EPOCH.fetch_add(1, Ordering::SeqCst);
    clear_acct_thread_caches();
}

/// Load and install an [`AcctModel`] from a JSON file path.
pub fn load_acct_model_from_file(path: &std::path::Path) -> Result<(), String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let model: AcctModel =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    set_active_acct_model(model);
    Ok(())
}

/// Read a copy of the currently active [`AcctModel`].
pub fn get_active_acct_model() -> AcctModel {
    *GLOBAL_MODEL_STORE.lock().expect("acct model mutex poisoned")
}

#[derive(Clone, Copy, Default)]
#[repr(C)]
struct LeafCacheSlot {
    k_lo: u64,
    k_hi: u64,
    val: f32,
    _pad: u32,
}

struct AcctThreadCtx {
    model_epoch: u64,
    model: AcctModel,
    cache_epoch_seen: u64,
    cache: Vec<LeafCacheSlot>,
}

impl AcctThreadCtx {
    fn new() -> Self {
        let mut model = *GLOBAL_MODEL_STORE.lock().expect("acct model mutex poisoned");
        if let Ok(path) = std::env::var("NC2000_ACCT_JSON") {
            if !path.is_empty() {
                if let Ok(text) = std::fs::read_to_string(&path) {
                    if let Ok(parsed) = serde_json::from_str::<AcctModel>(&text) {
                        model = parsed;
                    }
                }
            }
        }
        Self {
            model_epoch: GLOBAL_MODEL_EPOCH.load(Ordering::Relaxed),
            model,
            cache_epoch_seen: 0,
            cache: vec![LeafCacheSlot::default(); LEAF_CACHE_SLOTS],
        }
    }

    #[inline(always)]
    fn ensure_fresh(&mut self) {
        let ep = GLOBAL_MODEL_EPOCH.load(Ordering::Relaxed);
        if self.model_epoch != ep {
            self.model = *GLOBAL_MODEL_STORE.lock().expect("acct model mutex poisoned");
            self.model_epoch = ep;
            self.cache.fill(LeafCacheSlot::default());
        }
        let cep = CACHE_CLEAR_EPOCH.load(Ordering::Relaxed);
        if self.cache_epoch_seen != cep {
            self.cache.fill(LeafCacheSlot::default());
            self.cache_epoch_seen = cep;
        }
    }
}

static CACHE_CLEAR_EPOCH: AtomicU64 = AtomicU64::new(0);

thread_local! {
    static ACCT_CTX: RefCell<AcctThreadCtx> = RefCell::new(AcctThreadCtx::new());
}

/// Clear all thread-local leaf caches across all threads on next access.
pub fn clear_acct_thread_caches() {
    CACHE_CLEAR_EPOCH.fetch_add(1, Ordering::SeqCst);
    ACCT_CTX.with(|cell| {
        let mut ctx = cell.borrow_mut();
        ctx.cache.fill(LeafCacheSlot::default());
        ctx.cache_epoch_seen = CACHE_CLEAR_EPOCH.load(Ordering::Relaxed);
    });
}

